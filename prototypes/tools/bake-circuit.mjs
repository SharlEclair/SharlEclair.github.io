/**
 * Bake the Albert Park circuit centreline into `shared/transit/data/circuit.js`.
 *
 * Why this exists: the reference project's `src/data/ground.js` ships the circuit layer collapsed into
 * a ~14 m blob (all 2,250 vertices inside x 138..152, z 31..45), so the track never rendered. This
 * rebuilds it from the SAME cached OpenStreetMap responses the reference project already holds
 * (read-only), and places it in the city's own anchored metre plane by fitting an affine transform
 * through the A* trace's nodes - whose OSM ids and plane coordinates are both known - so no projection
 * library and no network access is needed.
 *
 *   node tools/bake-circuit.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const cacheDir = join(root, '..', 'transit-animation', '.cache', 'osmnx')
const { astarTrace } = await import('../shared/transit/data/astar-trace.js')

const CIRCUIT_ROADS = new Set([
  'Aughtie Drive', 'Lakeside Drive', 'Ross Gregory Drive',
  'Aquatic Drive', 'Village Green Drive', 'Hockey Drive',
])

// ---- load every cached Overpass response; collect node lat/lon and named ways ----------------------
const nodes = new Map()
const ways = new Map()
for (const file of readdirSync(cacheDir).filter((f) => f.endsWith('.json'))) {
  let data
  try { data = JSON.parse(readFileSync(join(cacheDir, file), 'utf8')) } catch { continue }
  for (const el of data.elements ?? []) {
    if (el.type === 'node' && typeof el.lat === 'number') nodes.set(el.id, [el.lat, el.lon])
    if (el.type === 'way' && el.tags?.highway && CIRCUIT_ROADS.has(el.tags.name) && el.nodes) {
      ways.set(el.id, { name: el.tags.name, nodes: el.nodes })
    }
  }
}

// ---- fit plane = A * [lon, lat, 1] through the trace nodes (least squares, normal equations) -------
const ids = astarTrace.nodes.ids
const rows = []
for (let i = 0; i < ids.length; i += 1) {
  const ll = nodes.get(Number(ids[i]))
  if (ll) rows.push([ll[1], ll[0], astarTrace.nodes.coords[i][0], astarTrace.nodes.coords[i][1]])
}
if (rows.length < 20) throw new Error(`only ${rows.length} trace nodes found in the OSM cache`)
const lon0 = rows.reduce((s, r) => s + r[0], 0) / rows.length
const lat0 = rows.reduce((s, r) => s + r[1], 0) / rows.length
function solve3(m, v) {
  const a = m.map((r, i) => [...r, v[i]])
  for (let c = 0; c < 3; c += 1) {
    let p = c
    for (let r = c + 1; r < 3; r += 1) if (Math.abs(a[r][c]) > Math.abs(a[p][c])) p = r
    ;[a[c], a[p]] = [a[p], a[c]]
    for (let r = 0; r < 3; r += 1) {
      if (r === c) continue
      const f = a[r][c] / a[c][c]
      for (let k = c; k < 4; k += 1) a[r][k] -= f * a[c][k]
    }
  }
  return a.map((r, i) => r[3] / r[i])
}
const M = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]
const bx = [0, 0, 0]
const by = [0, 0, 0]
for (const [lon, lat, x, y] of rows) {
  const f = [lon - lon0, lat - lat0, 1]
  for (let i = 0; i < 3; i += 1) {
    for (let j = 0; j < 3; j += 1) M[i][j] += f[i] * f[j]
    bx[i] += f[i] * x
    by[i] += f[i] * y
  }
}
const ax = solve3(M, bx)
const ay = solve3(M, by)
const toPlane = (lat, lon) => [
  ax[0] * (lon - lon0) + ax[1] * (lat - lat0) + ax[2],
  ay[0] * (lon - lon0) + ay[1] * (lat - lat0) + ay[2],
]
let worst = 0
for (const [lon, lat, x, y] of rows) {
  const p = toPlane(lat, lon)
  worst = Math.max(worst, Math.hypot(p[0] - x, p[1] - y))
}

// ---- polylines in the SHIPPING frame (x, z = -planeY), deduplicated ---------------------------------
const polylines = []
let length = 0
for (const way of ways.values()) {
  const pts = []
  for (const id of way.nodes) {
    const ll = nodes.get(id)
    if (!ll) continue
    const p = toPlane(ll[0], ll[1])
    pts.push([+p[0].toFixed(2), +(-p[1]).toFixed(2)])
  }
  if (pts.length < 2) continue
  for (let i = 1; i < pts.length; i += 1) length += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1])
  polylines.push({ name: way.name, points: pts })
}
const all = polylines.flatMap((p) => p.points)
const cx = all.reduce((s, p) => s + p[0], 0) / all.length
const cz = all.reduce((s, p) => s + p[1], 0) / all.length
const ext = all.reduce((e, p) => [Math.min(e[0], p[0]), Math.max(e[1], p[0]), Math.min(e[2], p[1]), Math.max(e[3], p[1])], [1e9, -1e9, 1e9, -1e9])

const out = `// GENERATED by tools/bake-circuit.mjs - do not edit by hand.
// Albert Park circuit centrelines in the shipping frame: [x, z] metres, Y-up, anchored like scene.glb.
// Source: OpenStreetMap (ODbL) via the reference project's Overpass cache. Fit residual ${worst.toFixed(2)} m
// over ${rows.length} trace nodes.
export const circuit = ${JSON.stringify({
    roads: [...CIRCUIT_ROADS],
    ways: polylines.length,
    lengthM: Math.round(length),
    centre: [+cx.toFixed(1), +cz.toFixed(1)],
    extent: ext.map((v) => +v.toFixed(1)),
    fitResidualM: +worst.toFixed(3),
    polylines: polylines.map((p) => p.points),
  })}
`
writeFileSync(join(root, 'shared', 'transit', 'data', 'circuit.js'), out)
console.log(JSON.stringify({ traceNodesMatched: rows.length, worstResidualM: +worst.toFixed(3), ways: polylines.length, lengthM: Math.round(length), centre: [cx, cz], extent: ext, names: [...new Set(polylines.map((p) => p.name))] }))
